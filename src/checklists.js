// Типы пунктов:
//   p    — паспорт объекта (факт: выбор одного варианта)
//   k    — проверка: Ок / Проблема (+ комментарий) / Н/П
//   flag — красный флаг ЕГРН: Нет / Есть (+ комментарий), «Есть» = уведомление
//   r    — выбор варианта
