// skip — раздел можно закрыть одной кнопкой: 'no' (флаги «Нет») или 'na' (всё «Н/П»)

function k(l, when) { return { t: 'k', l: l, when: when }; }
function f(l, when) { return { t: 'f', l: l, when: when }; }
function r(l, o, when) { return { t: 'r', l: l, o: o, when: when }; }
function p(id, l, o, when) { return { t: 'p', id: id, l: l, o: o, when: when }; }
function flag(id, l) { return { t: 'flag', id: id, l: l }; }
function docs(list) { return { t: 'docs', id: 'docs', l: 'Документы для подачи', o: list }; }

