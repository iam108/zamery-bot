var STAGES = ['Сбор документов', 'Подано', 'Выездная проверка', 'Решение получено', 'Архив'];

// Стабильные id по названию раздела и пункта — порядок можно менять, отметки не съедут
function hashId(s) { var h = 5381; for (var i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) | 0; return 'i' + (h >>> 0).toString(36); }
Object.keys(LISTS).forEach(function (key) {
  LISTS[key].sections = LISTS[key].sections.map(function (s) {
    var seen = {};
    return Object.assign({}, s, { i: s.i.map(function (it) {
      if (it.id) return it;
      var base = hashId(s.t + '|' + it.l); var id = base, n = 2;
      while (seen[id]) id = base + '_' + (n++);
      seen[id] = 1;
      return Object.assign({}, it, { id: id });
    }) });
  });
});

function pickChecklist(region, kind, service) {
  if (kind === 'Табак') return 'TAB'; // Москва и Санкт-Петербург — одинаковые требования
  var r0 = region === 'МО' ? 'MO' : 'MSK';
  var kk = kind === 'Общепит' ? 'OBSH' : 'MAG';
  if (service === 'Переоформление' && r0 === 'MO' && kk === 'MAG') return 'MO_MAG_RE';
  return r0 + '_' + kk;
}

function flagLabels(key) {
  var out = {};
  (LISTS[key] ? LISTS[key].sections : []).forEach(function (s) { s.i.forEach(function (it) { if (it.t === 'flag') out[it.id] = it.l; }); });
  return out;
}

